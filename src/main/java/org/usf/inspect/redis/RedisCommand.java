    public static RedisCommand parse(String command) {
        if(command == null || command.isBlank()) {
            return null;
        }
        try {
            return RedisCommand.valueOf(command.toUpperCase().replace(" ", "_").replace(".", "_").replace("-", "_"));
        } catch (IllegalArgumentException e) {
            log.error("Erreur lors du parsing de la commande Redis : "+command, e);
            return null;
        }
    }
