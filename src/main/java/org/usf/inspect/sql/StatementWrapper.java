package org.usf.inspect.sql;

import static java.util.Objects.isNull;
import static java.util.Objects.nonNull;
import static org.usf.inspect.core.InspectExecutor.call;
import static org.usf.inspect.core.InspectExecutor.exec;

import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.sql.Wrapper;

import org.usf.inspect.core.InspectExecutor.ExecutionListener;
import org.usf.inspect.core.SafeCallable;

import lombok.experimental.Delegate;

/**
 * 
 * @author u$f
 *
 */
public class StatementWrapper extends AbstractWrapper<Statement> implements Statement {

	@Delegate(excludes = Wrapper.class)
	protected final Statement st;
	protected final ConnectionWrapper connection;
	protected final StatementLifecycleTracer tracer;
	
	private ResultSetWrapper resultSet;

	public StatementWrapper(Statement st, ConnectionWrapper connection, StatementLifecycleTracer tracer) {
		super(st);
		this.st = st; // duplicated reference, cannot delegate in super class  
		this.connection = connection;
		this.tracer = tracer;
	}
	
	@Override
	public void addBatch(String sql) throws SQLException {
		exec(()-> st.addBatch(sql), tracer.addBatchStageListener(sql));
	}

	@Override
	public void clearBatch() throws SQLException {
		exec(st::clearBatch, tracer.clearBatchStage());
	}
	
	@Override
	public boolean execute(String sql) throws SQLException {
		return releaseAndExecute(()-> st.execute(sql), tracer.executeStageListener(sql));
	}
	
	@Override
	public boolean execute(String sql, int autoGeneratedKeys) throws SQLException {
		return releaseAndExecute(()-> st.execute(sql, autoGeneratedKeys), tracer.executeStageListener(sql));
	}
	
	@Override
	public boolean execute(String sql, int[] columnIndexes) throws SQLException {
		return releaseAndExecute(()-> st.execute(sql, columnIndexes), tracer.executeStageListener(sql));
	}
	
	@Override
	public boolean execute(String sql, String[] columnNames) throws SQLException {
		return releaseAndExecute(()-> st.execute(sql, columnNames), tracer.executeStageListener(sql));
	}
	
	@Override
	public int executeUpdate(String sql) throws SQLException {
		return releaseAndExecute(()-> st.executeUpdate(sql), tracer.executeUpdateStageListener(sql));
	}
	
	@Override
	public int executeUpdate(String sql, int autoGeneratedKeys) throws SQLException {
		return releaseAndExecute(()-> st.executeUpdate(sql, autoGeneratedKeys), tracer.executeUpdateStageListener(sql));
	}
	
	@Override
	public int executeUpdate(String sql, int[] columnIndexes) throws SQLException {
		return releaseAndExecute(()-> st.executeUpdate(sql, columnIndexes), tracer.executeUpdateStageListener(sql));
	}
	
	@Override
	public int executeUpdate(String sql, String[] columnNames) throws SQLException {
		return releaseAndExecute(()-> st.executeUpdate(sql, columnNames), tracer.executeUpdateStageListener(sql));
	}

	@Override
	public int[] executeBatch() throws SQLException {
		return releaseAndExecute(st::executeBatch, tracer.executeBatchStageListener());
	}
	
	@Override
	public long executeLargeUpdate(String sql) throws SQLException {
		return releaseAndExecute(()-> st.executeLargeUpdate(sql), tracer.executeUpdateStageListener(sql));
	}
	
	@Override
	public long executeLargeUpdate(String sql, int autoGeneratedKeys) throws SQLException {
		return releaseAndExecute(()-> st.executeLargeUpdate(sql, autoGeneratedKeys), tracer.executeUpdateStageListener(sql));
	}
	
	@Override
	public long executeLargeUpdate(String sql, int[] columnIndexes) throws SQLException {
		return releaseAndExecute(()-> st.executeLargeUpdate(sql, columnIndexes), tracer.executeUpdateStageListener(sql));
	}
	
	@Override
	public long executeLargeUpdate(String sql, String[] columnNames) throws SQLException {
		return releaseAndExecute(()-> st.executeLargeUpdate(sql, columnNames), tracer.executeUpdateStageListener(sql));
	}
	
	@Override
	public long[] executeLargeBatch() throws SQLException {
		return releaseAndExecute(st::executeLargeBatch, tracer.executeLargeBatchStageListener());
	}
	
	<T> T releaseAndExecute(SafeCallable<T,SQLException> fn, ExecutionListener<? super T> listener) throws SQLException {
		releaseCurrentResultSet(); // release current result set, if any, before moving to next result set
		return call(fn, listener);
	}
	
	@Override
	public ResultSet executeQuery(String sql) throws SQLException {
		return releaseAndExecuteQuery(()-> st.executeQuery(sql), tracer.executeStageListener(sql));
	}
	
	ResultSet releaseAndExecuteQuery(SafeCallable<ResultSet,SQLException> fn, ExecutionListener<? super ResultSet> listener) throws SQLException {
		releaseCurrentResultSet(); // release current result set, if any, before moving to next result set
		this.resultSet = connection.resultSet(fn, listener, this);
		return resultSet;
	}
	
	@Override
	public ResultSet getResultSet() throws SQLException {
		var rs = st.getResultSet();
		if(isNull(rs)) {
			resultSet = null;
		}
		else if(isNull(resultSet) || resultSet.rs != rs) {
			resultSet = connection.resultSet(rs, this);
		}
		return resultSet;
	}
	
	@Override
	public int getUpdateCount() throws SQLException {
		var n = st.getUpdateCount();
		tracer.updateStageRowsCount(n);
		return n;
	}
	
	@Override
	public long getLargeUpdateCount() throws SQLException {
		var n = st.getLargeUpdateCount();
		tracer.updateStageRowsCount(n);
		return n;
	}
	
	@Override
	public boolean getMoreResults() throws SQLException {
		var more = st.getMoreResults();
		releaseCurrentResultSet(); // release current result set, if any, before moving to next result set
		tracer.onMoreResults();
		return more;
	}
	
	@Override
	public boolean getMoreResults(int current) throws SQLException {
		var more = st.getMoreResults(current);
		if(current != KEEP_CURRENT_RESULT) {
			releaseCurrentResultSet(); // release current result set, if any, before moving to next result set
		}
		tracer.onMoreResults();
		return more;
	}
	
	@Override
	public Connection getConnection() throws SQLException {
		return connection;
	}
	
	@Override
	public void close() throws SQLException {
		try {
			st.close();
		}
		finally {
			releaseCurrentResultSet();
			connection.releaseWrapper(this); //remove this statement from the connection wrapper to avoid memory leak
		}
	}
	
	@Override
	protected void ensureTraced() {
		tracer.emitCurrentExecutionStage();
	}
	
	void releaseCurrentResultSet() {
		if(nonNull(resultSet)) {
			connection.releaseWrapper(resultSet);
			resultSet = null;
		}
	}
}
