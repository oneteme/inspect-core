package org.usf.inspect.sql;

import static java.util.Objects.nonNull;
import static org.usf.inspect.DatabaseAction.COMMIT;
import static org.usf.inspect.DatabaseAction.METADATA;
import static org.usf.inspect.DatabaseAction.ROLLBACK;
import static org.usf.inspect.DatabaseAction.SAVEPOINT;
import static org.usf.inspect.DatabaseCommand.SET;
import static org.usf.inspect.core.InspectExecutor.call;
import static org.usf.inspect.core.InspectExecutor.exec;

import java.sql.CallableStatement;
import java.sql.Connection;
import java.sql.DatabaseMetaData;
import java.sql.PreparedStatement;
import java.sql.SQLException;
import java.sql.Savepoint;
import java.sql.Statement;

import lombok.Getter;
import lombok.RequiredArgsConstructor;
import lombok.experimental.Delegate;

/**
 * 
 * @author u$f
 
 */
@RequiredArgsConstructor
public final class ConnectionWrapper implements Connection {
	
	@Delegate
	private final Connection cn;
	@Getter(lombok.AccessLevel.PACKAGE)
	private final DatabaseConnectionLifecycleTracer tracer;

	@Override
	public Statement createStatement() throws SQLException {
		var st = tracer.newStatementTracer(false);
		return new StatementWrapper(call(cn::createStatement, st.statementStageListener(null)), this, st);
	}
	
	@Override
	public Statement createStatement(int resultSetType, int resultSetConcurrency) throws SQLException {
		var st = tracer.newStatementTracer(false);
		return new StatementWrapper(call(()-> cn.createStatement(resultSetType, resultSetConcurrency), st.statementStageListener(null)), this, st);
	}
	
	@Override
	public Statement createStatement(int resultSetType, int resultSetConcurrency, int resultSetHoldability) throws SQLException {
		var st = tracer.newStatementTracer(false);
		return new StatementWrapper(call(()-> cn.createStatement(resultSetType, resultSetConcurrency, resultSetHoldability), st.statementStageListener(null)), this, st);
	}
	
	@Override
	public PreparedStatement prepareStatement(String sql) throws SQLException {
		var st = tracer.newStatementTracer(true);
		return new PreparedStatementWrapper(call(()-> cn.prepareStatement(sql), st.statementStageListener(sql)), this, st);
	}
	
	@Override
	public PreparedStatement prepareStatement(String sql, int resultSetType, int resultSetConcurrency) throws SQLException {
		var st = tracer.newStatementTracer(true);
		return new PreparedStatementWrapper(call(()-> cn.prepareStatement(sql, resultSetType, resultSetConcurrency), st.statementStageListener(sql)), this, st);
	}
	
	@Override
	public PreparedStatement prepareStatement(String sql, int resultSetType, int resultSetConcurrency, int resultSetHoldability) throws SQLException {
		var st = tracer.newStatementTracer(true);
		return new PreparedStatementWrapper(call(()-> cn.prepareStatement(sql, resultSetType, resultSetConcurrency, resultSetHoldability), st.statementStageListener(sql)), this, st);
	}
	
	@Override
	public PreparedStatement prepareStatement(String sql, int autoGeneratedKeys) throws SQLException {
		var st = tracer.newStatementTracer(true);
		return new PreparedStatementWrapper(call(()-> cn.prepareStatement(sql, autoGeneratedKeys), st.statementStageListener(sql)), this, st);
	}
	
	@Override
	public PreparedStatement prepareStatement(String sql, int[] columnIndexes) throws SQLException {
		var st = tracer.newStatementTracer(true);
		return new PreparedStatementWrapper(call(()-> cn.prepareStatement(sql, columnIndexes), st.statementStageListener(sql)), this, st);
	}
	
	@Override
	public PreparedStatement prepareStatement(String sql, String[] columnNames) throws SQLException {
		var st = tracer.newStatementTracer(true);
		return new PreparedStatementWrapper(call(()-> cn.prepareStatement(sql, columnNames), st.statementStageListener(sql)), this, st);
	}
	
	@Override
	public CallableStatement prepareCall(String sql) throws SQLException {
		var st = tracer.newStatementTracer(true);
		return new CallableStatementWrapper(call(()-> cn.prepareCall(sql), st.statementStageListener(sql)), this, st);
	}
	
	@Override
	public CallableStatement prepareCall(String sql, int resultSetType, int resultSetConcurrency) throws SQLException {
		var st = tracer.newStatementTracer(true);
		return new CallableStatementWrapper(call(()-> cn.prepareCall(sql, resultSetType, resultSetConcurrency), st.statementStageListener(sql)), this, st);
	}
	
	@Override
	public CallableStatement prepareCall(String sql, int resultSetType, int resultSetConcurrency, int resultSetHoldability) throws SQLException {
		var st = tracer.newStatementTracer(true);
		return new CallableStatementWrapper(call(()-> cn.prepareCall(sql, resultSetType, resultSetConcurrency, resultSetHoldability), st.statementStageListener(sql)), this, st);
	}
	
	@Override
	public Savepoint setSavepoint() throws SQLException {
		return call(cn::setSavepoint, tracer.stageListener(SAVEPOINT));
	}
	
	@Override
	public Savepoint setSavepoint(String name) throws SQLException {
		return call(()-> cn.setSavepoint(name), tracer.stageListener(SAVEPOINT, name));
	}
	
	@Override
	public void commit() throws SQLException {
		exec(cn::commit, tracer.stageListener(COMMIT));
	}
	
	@Override
	public void rollback() throws SQLException {
		exec(cn::rollback, tracer.stageListener(ROLLBACK));
	}
	
	@Override
	public void rollback(Savepoint savepoint) throws SQLException {
		var name = nonNull(savepoint) ? savepoint.getSavepointName() : null;
		exec(()-> cn.rollback(savepoint), tracer.stageListener(ROLLBACK, name));
	}
	
	@Override
	public DatabaseMetaData getMetaData() throws SQLException {
		return new DatabaseMetaDataWrapper(call(cn::getMetaData, tracer.stageListener(METADATA)), this);
	}
	
	@Override
	public void setCatalog(String catalog) throws SQLException {
		 exec(()-> cn.setCatalog(catalog), tracer.executeStageListener(SET, "catalog="+catalog));
	}
	
	@Override
	public void setSchema(String schema) throws SQLException {
		 exec(()-> cn.setSchema(schema), tracer.executeStageListener(SET, "schema="+schema));
	}
	
	@Override
	public void setAutoCommit(boolean autoCommit) throws SQLException {
		 exec(()-> cn.setAutoCommit(autoCommit), tracer.executeStageListener(SET, "autoCommit="+autoCommit));
	}
	
	@Override
	public void close() throws SQLException {
		exec(cn::close, tracer.disconnectionListener());
	}
}
