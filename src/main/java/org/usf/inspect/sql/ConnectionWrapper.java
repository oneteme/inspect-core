package org.usf.inspect.sql;

import static java.util.Collections.newSetFromMap;
import static org.usf.inspect.DatabaseAction.ABORT;
import static org.usf.inspect.DatabaseAction.DISCONNECTION;
import static org.usf.inspect.DatabaseAction.METADATA;
import static org.usf.inspect.DatabaseCommand.COMMIT;
import static org.usf.inspect.DatabaseCommand.RELEASE;
import static org.usf.inspect.DatabaseCommand.ROLLBACK;
import static org.usf.inspect.DatabaseCommand.SAVEPOINT;
import static org.usf.inspect.DatabaseCommand.SET;
import static org.usf.inspect.core.Constants.REPORTER;
import static org.usf.inspect.core.InspectExecutor.call;
import static org.usf.inspect.core.InspectExecutor.exec;

import java.sql.CallableStatement;
import java.sql.Connection;
import java.sql.DatabaseMetaData;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Savepoint;
import java.sql.Statement;
import java.sql.Wrapper;
import java.util.IdentityHashMap;
import java.util.Set;
import java.util.concurrent.Executor;

import org.usf.inspect.DatabaseAction;
import org.usf.inspect.core.InspectExecutor.ExecutionListener;
import org.usf.inspect.core.SafeCallable;
import org.usf.inspect.core.SafeCallable.SafeRunnable;

import lombok.AccessLevel;
import lombok.Getter;
import lombok.experimental.Delegate;

/**
 * 
 * @author u$f
 
 */
public final class ConnectionWrapper extends AbstractWrapper<Connection> implements Connection {

	@Delegate(excludes = Wrapper.class)
	private final Connection cn;
	@Getter(AccessLevel.PACKAGE)
	private final DatabaseConnectionLifecycleTracer tracer;
	private final Set<AbstractWrapper<?>> wrappers = newSetFromMap(new IdentityHashMap<>());
	
	private boolean closed;
	
	public ConnectionWrapper(Connection cn, DatabaseConnectionLifecycleTracer tracer) {
		super(cn); 
		this.cn = cn; // duplicated reference, cannot delegate in super class 
		this.tracer = tracer;
	}

	@Override
	public Statement createStatement() throws SQLException {
		return statement(cn::createStatement);
	}
	
	@Override
	public Statement createStatement(int resultSetType, int resultSetConcurrency) throws SQLException {
		return statement(()-> cn.createStatement(resultSetType, resultSetConcurrency));
	}
	
	@Override
	public Statement createStatement(int resultSetType, int resultSetConcurrency, int resultSetHoldability) throws SQLException {
		return statement(()-> cn.createStatement(resultSetType, resultSetConcurrency, resultSetHoldability));
	}
	
	@Override
	public PreparedStatement prepareStatement(String sql) throws SQLException {
		return prepareStatement(sql, ()-> cn.prepareStatement(sql));
	}
	
	@Override
	public PreparedStatement prepareStatement(String sql, int resultSetType, int resultSetConcurrency) throws SQLException {
		return prepareStatement(sql, ()-> cn.prepareStatement(sql, resultSetType, resultSetConcurrency));
	}
	
	@Override
	public PreparedStatement prepareStatement(String sql, int resultSetType, int resultSetConcurrency, int resultSetHoldability) throws SQLException {
		return prepareStatement(sql, ()-> cn.prepareStatement(sql, resultSetType, resultSetConcurrency, resultSetHoldability));
	}
	
	@Override
	public PreparedStatement prepareStatement(String sql, int autoGeneratedKeys) throws SQLException {
		return prepareStatement(sql, ()-> cn.prepareStatement(sql, autoGeneratedKeys));
	}
	
	@Override
	public PreparedStatement prepareStatement(String sql, int[] columnIndexes) throws SQLException {
		return prepareStatement(sql, ()-> cn.prepareStatement(sql, columnIndexes));
	}
	
	@Override
	public PreparedStatement prepareStatement(String sql, String[] columnNames) throws SQLException {
		return prepareStatement(sql, ()-> cn.prepareStatement(sql, columnNames));
	}
	
	@Override
	public CallableStatement prepareCall(String sql) throws SQLException {
		return prepareCall(sql, ()-> cn.prepareCall(sql));
	}
	
	@Override
	public CallableStatement prepareCall(String sql, int resultSetType, int resultSetConcurrency) throws SQLException {
		return prepareCall(sql, ()-> cn.prepareCall(sql, resultSetType, resultSetConcurrency));
	}
	
	@Override
	public CallableStatement prepareCall(String sql, int resultSetType, int resultSetConcurrency, int resultSetHoldability) throws SQLException {
		return prepareCall(sql, ()-> cn.prepareCall(sql, resultSetType, resultSetConcurrency, resultSetHoldability));
	}
	
	@Override
	public Savepoint setSavepoint() throws SQLException {
		return call(cn::setSavepoint, tracer.executeStageListener(SAVEPOINT));
	}
	
	@Override
	public Savepoint setSavepoint(String name) throws SQLException {
		return call(()-> cn.setSavepoint(name), tracer.executeStageListener(SAVEPOINT, name));
	}
	
	@Override
	public void commit() throws SQLException {
		exec(cn::commit, tracer.executeStageListener(COMMIT));
	}
	
	@Override
	public void rollback() throws SQLException {
		exec(cn::rollback, tracer.executeStageListener(ROLLBACK));
	}
	
	@Override
	public void rollback(Savepoint savepoint) throws SQLException {
		exec(()-> cn.rollback(savepoint), tracer.executeStageListener(ROLLBACK, "SAVEPOINT")); //savepoint.name may throw exception in some drivers
	}

	@Override
	public void releaseSavepoint(Savepoint savepoint) throws SQLException {
		exec(()-> cn.releaseSavepoint(savepoint), tracer.executeStageListener(RELEASE, "SAVEPOINT")); //savepoint.name may throw exception in some drivers
	}
	
	@Override
	public DatabaseMetaData getMetaData() throws SQLException {
		return new DatabaseMetaDataWrapper(call(cn::getMetaData, tracer.stageListener(METADATA, null)), this);
	}
	
	@Override
	public void setCatalog(String catalog) throws SQLException {
		 exec(()-> cn.setCatalog(catalog), tracer.executeStageListener(SET, "catalog="+catalog));
	}
	
	@Override
	public void setSchema(String schema) throws SQLException {
		 exec(()-> cn.setSchema(schema), tracer.executeStageListener(SET, "schema="+schema));
	}
	
	@Override
	public void setAutoCommit(boolean autoCommit) throws SQLException {
		 exec(()-> cn.setAutoCommit(autoCommit), tracer.executeStageListener(SET, "autoCommit="+autoCommit));
	}
	
	@Override
	public void setNetworkTimeout(Executor executor, int milliseconds) throws SQLException {
		 exec(()-> cn.setNetworkTimeout(executor, milliseconds), tracer.executeStageListener(SET, "timeout="+milliseconds));
	}
	
	@Override
	public void abort(Executor executor) throws SQLException {
		disconnect(()-> cn.abort(executor), ABORT);
	}

	@Override
	public void close() throws SQLException {
		disconnect(cn::close, DISCONNECTION);
	}
	
	void disconnect(SafeRunnable<SQLException> run, DatabaseAction action) throws SQLException {
		if(closed) { //avoid double tracing
			run.run();
		}
		else {
			try {
				releaseWrappers();
				exec(run, tracer.disconnectionListener(action));
			}
			finally {
				closed = true;
			}
		}
	}
	
	void releaseWrappers() {
		if(!wrappers.isEmpty()) {
			for(var w: wrappers) {
				try {
					w.ensureTraced();
				}
				catch (Exception e) {
					REPORTER.error("ConnectionWrapper.releaseWrappers: Failed to ensure tracing for {}", w, e);
				}
			}
			wrappers.clear();
		}
	}
	
	void releaseWrapper(AbstractWrapper<?> wrapper) {
		if(wrappers.contains(wrapper)) {
			try {
				wrapper.ensureTraced();
			}
			catch (Exception e) {
				REPORTER.error("ConnectionWrapper.releaseWrapper: Failed to ensure tracing for {}", wrapper, e);
			}
			wrappers.remove(wrapper);
		}
	}
	
	StatementWrapper statement(SafeCallable<Statement, SQLException> fn) throws SQLException {
		var trc = tracer.newStatementTracer(false);
		var wrp = new StatementWrapper(call(fn, trc.statementStageListener(null)), this, trc);
		wrappers.add(wrp);
		return wrp;
	}
	
	PreparedStatementWrapper prepareStatement(String sql, SafeCallable<PreparedStatement, SQLException> fn) throws SQLException {
		var trc = tracer.newStatementTracer(true);
		var wrp = new PreparedStatementWrapper(call(fn, trc.statementStageListener(sql)), this, trc);
		wrappers.add(wrp);
		return wrp;
	}
	
	CallableStatementWrapper prepareCall(String sql, SafeCallable<CallableStatement, SQLException> fn) throws SQLException {
		var trc = tracer.newStatementTracer(true);
		var wrp = new CallableStatementWrapper(call(fn, trc.statementStageListener(sql)), this, trc);
		wrappers.add(wrp);
		return wrp;
	}
	
	ResultSetWrapper resultSet(SafeCallable<ResultSet, SQLException> fn, ExecutionListener<? super ResultSet> listener, StatementWrapper statement) throws SQLException {
		return resultSet(call(fn, listener), statement);
	}

	ResultSetWrapper resultSet(ResultSet resultSet, StatementWrapper statement) {
		var wrp = new ResultSetWrapper(resultSet, this, statement);
		wrappers.add(wrp);
		return wrp;
	}
}
